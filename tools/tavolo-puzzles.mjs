// Tavolo Baso — builds the bank of original "matto in 2" positions for the chess puzzle of the day.
//   node tools/tavolo-puzzles.mjs [count=150] [seed=7]   → writes src/tavolo/chess/puzzles.js
// Positions are generated (not copied from any collection): a defending king on its own side with a pawn
// shelter and a few defenders, an attacking army with king; kept only when the side to move has a mate in
// exactly two with one single key move (no mate in one), checked by the engine's exhaustive mate solver.
import { writeFileSync } from 'node:fs';
import { Position } from '../src/tavolo/chess/core.js';
import { mateIn, mateKeys } from '../src/tavolo/chess/ai.js';

const COUNT = +(process.argv[2] || 150), SEED = +(process.argv[3] || 7);
let x = SEED * 2654435761 >>> 0 || 1;
const rnd = () => { x ^= x << 13; x ^= x >>> 17; x ^= x << 5; return (x >>> 0) / 4294967296; };
const ri = (n) => Math.floor(rnd() * n);
const pick = (a) => a[ri(a.length)];

function candidate() {
  // build with White attacking, Black defending; mirrored to Black attacking half of the time at the end
  const g = Array.from({ length: 8 }, () => Array(8).fill(null)); // g[rank][file]
  const free = (r, f) => r >= 0 && r < 8 && f >= 0 && f < 8 && !g[r][f];
  const put = (ch, r, f) => { if (!free(r, f)) return false; g[r][f] = ch; return true; };
  const kr = 7 - (rnd() < 0.75 ? 0 : 1), kf = pick([0, 1, 2, 5, 6, 7, 6, 6, 1, 3, 4]);
  put('k', kr, kf);
  // shelter pawns
  for (const df of [-1, 0, 1]) if (rnd() < 0.75) put('p', kr - 1 - (rnd() < 0.25 ? 1 : 0), kf + df);
  const extraDef = ri(3);
  for (let i = 0; i < extraDef; i++) { const ch = pick(['r', 'b', 'n', 'p', 'p', 'q', 'r']); for (let t = 0; t < 20; t++) if (put(ch, ch === 'p' ? 3 + ri(4) : 2 + ri(6), ri(8))) break; }
  // attacker
  for (let t = 0; t < 50; t++) if (put('K', ri(3), ri(8))) break;
  const army = pick([['Q', 'R'], ['Q', 'B'], ['Q', 'N'], ['R', 'R'], ['R', 'B'], ['R', 'N'], ['Q', 'R', 'B'], ['R', 'B', 'N'], ['Q', 'N', 'B'], ['R', 'R', 'B'], ['Q'], ['Q', 'R', 'N']]);
  for (const ch of army) for (let t = 0; t < 30; t++) if (put(ch, 1 + ri(7), ri(8))) break;
  const pawns = ri(4);
  for (let i = 0; i < pawns; i++) for (let t = 0; t < 20; t++) if (put('P', 1 + ri(5), ri(8))) break;
  // no pawns on the first or last rank
  for (const f of [0, 1, 2, 3, 4, 5, 6, 7]) for (const r of [0, 7]) if (g[r][f] === 'p' || g[r][f] === 'P') g[r][f] = null;
  let fen = '';
  for (let r = 7; r >= 0; r--) { let e = 0; for (let f = 0; f < 8; f++) { const c = g[r][f]; if (!c) { e++; continue; } if (e) { fen += e; e = 0; } fen += c; } if (e) fen += e; if (r) fen += '/'; }
  return fen + ' w - - 0 1';
}
// colours swapped and board flipped: same puzzle with Black to move
function mirror(fen) {
  const [b] = fen.split(' ');
  const rows = b.split('/').reverse().map((r) => [...r].map((c) => (/[a-z]/.test(c) ? c.toUpperCase() : /[A-Z]/.test(c) ? c.toLowerCase() : c)).join(''));
  return rows.join('/') + ' b - - 0 1';
}

const out = [], seen = new Set();
const t0 = Date.now(); let tried = 0;
while (out.length < COUNT && Date.now() - t0 < 15 * 60e3) {
  tried++;
  let fen = candidate(), p;
  try { p = new Position(fen); } catch { continue; }
  const wk = p.kings[0], bk = p.kings[1];
  if (Math.abs((wk >> 4) - (bk >> 4)) <= 1 && Math.abs((wk & 7) - (bk & 7)) <= 1) continue;
  if (p.inCheck(1) || p.inCheck(0)) continue;
  if (p.legal().length < 8) continue;
  if (mateIn(p, 1)) continue;
  // the defender must have something to do: not stalemated-ish, a few replies
  const keys = mateKeys(p, 2);
  if (keys.length !== 1) continue;
  // after the key the defender needs at least two replies (a real "two-mover")
  p.make(keys[0]); const replies = p.legal().length; const isCheck = p.inCheck(); p.unmake();
  if (replies < 2) continue;
  if (isCheck && rnd() < 0.6) continue; // prefer quiet keys
  if (out.length % 2) fen = mirror(fen);
  const q = new Position(fen); const key = mateKeys(q, 2);
  if (key.length !== 1) continue;
  const id = fen.split(' ')[0]; if (seen.has(id)) continue; seen.add(id);
  out.push({ fen, key: q.uci(key[0]), check: isCheck ? 1 : 0 });
  if (out.length % 10 === 0) console.log(out.length, 'puzzles,', tried, 'tried,', Math.round((Date.now() - t0) / 1000) + 's');
}
const body = `// Generated by tools/tavolo-puzzles.mjs (${out.length} original "matto in 2" positions, verified by the mate solver).\n// Each: fen (side to move mates in two), key = the only first move (UCI), check = the key gives check.\nexport const MATE2 = [\n${out.map((o) => `  ${JSON.stringify(o)},`).join('\n')}\n];\n`;
writeFileSync('src/tavolo/chess/puzzles.js', body);
console.log('wrote', out.length, 'puzzles from', tried, 'candidates in', Math.round((Date.now() - t0) / 1000), 's');
