// Pre-generates the jam bank for the «Ingorgo lampo» minigame with Ingorgo's own seeded generator, so the
// party never pauses mid-game to build a level: node tools/festa-bank.mjs -> src/festa/data/ingorgo-bank.js
import { writeFileSync, mkdirSync } from 'node:fs';
import { generate } from '../src/ingorgo/gen.js';

const out = [];
for (let j = 0; j < 24; j++) {
  const d = 0.04 + (j % 6) * 0.04;
  const L = generate(4242 + j * 7919, 'classico', d);
  out.push({ w: L.w, h: L.h, goal: L.goal, cars: L.cars.map(({ x, y, len, ax, dir, kind, hero }) => ({ x, y, len, ax, dir, kind, ...(hero ? { hero: true } : {}) })), walls: L.walls || [], opt: L.opt });
}
mkdirSync('src/festa/data', { recursive: true });
writeFileSync('src/festa/data/ingorgo-bank.js', `// Generated by tools/festa-bank.mjs with src/ingorgo/gen.js (classico, easy): ${out.length} jams, optimal moves ${out.map((l) => l.opt).join(',')}\nexport const JAMS = ${JSON.stringify(out)};\n`);
console.log('jams', out.length, out.map((l) => l.opt).join(','));
